#!/usr/bin/env python3
"""Write src/vm_compat_desc.inc: description text -> Modbus buffer pairs for vm_compat.c.
Every "...DescriptionBuf" tag whose text tag is defined in this build (include/vm_params.h)."""
import csv, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); APP = os.path.join(HERE, "..")
dd = {r["name"]: r for r in csv.DictReader(open(sys.argv[1], newline="", encoding="utf-8"))}
defined = set(re.findall(r"extern \w+ (vmx_\w+)", open(os.path.join(APP, "include", "vm_params.h")).read()))
def key(n): return re.sub(r"_+", "_", re.sub(r"[^A-Za-z0-9_]", "_", n)).strip("_")
out = ["/* vm_compat_desc.inc - GENERATED by tools/gen_compat_desc.py: description text -> Modbus buffer",
       " * pairs (vm_compat.c), every \"...DescriptionBuf\" whose text tag is defined in this build. */"]
skipped = []
for n in sorted(dd):
    if n.endswith("Buf") and "Description" in n:
        t = n[:-3]; b = "vmx_" + key(n); tv = "vmx_" + key(t)
        if t in dd and b in defined and tv in defined: out.append(f"DESC({b}, {tv});")
        else: skipped.append(n)
out.append("/* not copied (the text is a RAM tag of the old HMI with no home yet): " + ", ".join(skipped) + " */")
open(os.path.join(APP, "src", "vm_compat_desc.inc"), "w").write("\n".join(out) + "\n")
print(f"gen_compat_desc: {len(out) - 3} pairs, {len(skipped)} skipped")
