/* modbus_map.c - writes the Modbus register map of a build from its tables (the platform's
 * block and the application's map), as Markdown: the communications document the integrator
 * gets (CIP-14.4, 26.7) and the interface snapshot that make test compares (spec 9.3,
 * CIP-14.5). An address that moves or a value that goes shows up as a difference, which needs
 * a new map version (mb_ident_t.map_version) for the product, or a MINOR/MAJOR core version
 * for the platform's block.
 *
 *   build/modbus_map-<app>    the map of the application linked in (APP=) */
#include <stdio.h>
#include <string.h>
#include "plat_tasks.h"
#include "modbus.h"
#include "param.h"
#include "plat_version.h"

static const char *const tname[] = { "Coils", "Discrete inputs", "Holding registers", "Input registers" };
static const char *const fname[] = { "bit", "u16", "i16", "u32", "i32", "f32", "bytes", "array" };

static void cell(const char *s) {
    for (; s && *s; ++s) { if (*s == '|') fputs("\\|", stdout); else putchar(*s); }
}

int main(void) {
    const plat_app_t *app = app_select();
    if (param_init(app->params, app->n_params) != PERR_OK) { fprintf(stderr, "param table error at %u\n", param_table_error()); return 1; }
    int e = mb_init(app->modbus_map, app->n_modbus_map, &app->ident);
    if (e) { fprintf(stderr, "modbus map error at entry %d\n", e - 1); return 1; }
    printf("# %s: Modbus register map\n\n", app->ident.product);
    printf("Map version %u (input register 9001), platform block layout %u, core %s. **Generated by "
           "`make modbus-map` from the firmware's tables (`tools/modbus_map.c`); do not edit by hand.** "
           "`make test` fails if it no longer matches the firmware: a moved address or a removed value "
           "needs a new map version (CIP-14.5).\n\n",
           app->ident.map_version, PLAT_MB_BLOCK_VERSION, PLAT_CORE_VERSION);
    puts("Addresses are 0-based (protocol addresses). 32-bit values: high word first unless the entry says "
         "\"low word first\". Text and bytes: two bytes per register, first byte in the high half unless "
         "it says \"low byte first\". Input registers 9000-9199 are the platform's block, the same in "
         "every product.\n");
    int last_t = -1;
    for (size_t i = 0; i < mb_entry_count(); ++i) {
        uint16_t span = 0;
        const mb_map_t *m = mb_entry_at(i, &span);
        const param_def_t *d = param_find(m->id);
        if (m->table != last_t) {
            printf("%s## %s\n\n| Address | Count | Format | Parameter | Name | Unit | Access | Notes |\n|---|---|---|---|---|---|---|---|\n",
                   last_t < 0 ? "" : "\n", tname[m->table]);
            last_t = m->table;
        }
        bool ro = !d || (d->flags & PF_RO) || m->table == MB_INPUT || m->table == MB_DISCRETE || (d->flags & PF_NO_MODBUS);
        printf("| %u | %u | %s | %u | `", m->addr, span, fname[m->fmt], m->id);
        cell(d ? d->name : "?");
        fputs("` | ", stdout);
        cell(d && d->unit ? d->unit : "");
        printf(" | %s | ", ro ? "read" : d->level >= PLAT_LVL_FACTORY ? "read/write (factory)" : "read/write");
        const char *sep = "";
        if (m->flags & MBF_WORD_LO_FIRST) { printf("%slow word first", sep); sep = ", "; }
        if (m->flags & MBF_BYTE_LO_FIRST) { printf("%slow byte first", sep); sep = ", "; }
        if (m->dec) { printf("%svalue x 10^%d", sep, m->dec); sep = ", "; }
        if (m->table == MB_INPUT && m->addr >= PLAT_MB_BLOCK_ADDR && m->addr <= PLAT_MB_BLOCK_END) { printf("%splatform block", sep); sep = ", "; }
        puts(" |");
    }
    return 0;
}
