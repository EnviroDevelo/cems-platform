#!/usr/bin/env python3
"""The product's firmware-signing key (decision D14). The private key is a tech-level
credential: keep it on the technicians' build machine, never in the repository.

    tools/fwkey.py new  cems-fw-key.pem                    # make a key pair (once, for the product)
    tools/fwkey.py pubkey cems-fw-key.pem > platform/core/fw_pubkey.c   # build it into the firmware
    tools/fwkey.py hex  cems-fw-key.pem                    # the public key as hex (tests, netsim)

Then sign every image: tools/mkfwimage.py build.bin out.cfw --version x.y.z --key cems-fw-key.pem
Uses Python's 'cryptography' package if present, otherwise the openssl command."""
import subprocess, sys


def public_point(pem_path):
    """65-byte uncompressed P-256 public point of a private key."""
    try:
        from cryptography.hazmat.primitives import serialization
        k = serialization.load_pem_private_key(open(pem_path, "rb").read(), password=None)
        return k.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
    except ImportError:
        der = subprocess.run(["openssl", "ec", "-in", pem_path, "-pubout", "-outform", "DER"],
                             capture_output=True, check=True).stdout
        return der[-65:]                       # SubjectPublicKeyInfo ends with the point


def new_key(path):
    try:
        from cryptography.hazmat.primitives.asymmetric import ec
        from cryptography.hazmat.primitives import serialization
        k = ec.generate_private_key(ec.SECP256R1())
        pem = k.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption())
        open(path, "wb").write(pem)
    except ImportError:
        subprocess.run(["openssl", "ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", path], check=True)
    print(f"{path}: new P-256 signing key. Keep it safe: anyone with it can make firmware the units accept.")


def c_file(q):
    rows = ",\n    ".join(", ".join(f"0x{b:02x}" for b in q[k:k + 13]) for k in range(0, 65, 13))
    return f"""/* fw_pubkey.c - GENERATED by tools/fwkey.py: the product's firmware-signing public
 * key (decision D14). Images not signed with the matching private key are refused. */
#include "fw_update.h"

const uint8_t fw_pubkey[65] = {{
    {rows}
}};
const bool    fw_pubkey_present = true;
"""


def main():
    if len(sys.argv) != 3 or sys.argv[1] not in ("new", "pubkey", "hex"):
        print(__doc__); return 2
    cmd, path = sys.argv[1], sys.argv[2]
    if cmd == "new":
        new_key(path)
    elif cmd == "pubkey":
        sys.stdout.write(c_file(public_point(path)))
    else:
        print(public_point(path).hex())
    return 0


if __name__ == "__main__":
    sys.exit(main())
