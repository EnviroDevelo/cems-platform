#!/usr/bin/env python3
"""Make the touchscreen's own fonts (decision D24): DejaVu Sans rendered at the sizes of
the BT817 ROM fonts the UI uses, as EVE "legacy" L4 bitmap fonts (148-byte metric block +
4-bit glyph cells), zlib-compressed for CMD_INFLATE, written as C arrays:

    tools/mkfont.py [platform/ui/eve_fonts.c]

The ROM fonts only have ASCII, so a unit like "mg/m³" or "°C" cannot be shown. These
fonts have ASCII 32..126 and, in the otherwise unused codes 1..31, the symbols in EXTRA
below; the UI converts UTF-8 text to that code (ui.c, eve_font_encode). Anything else
shows as '?'.

DejaVu fonts: Bitstream Vera licence (free to embed and redistribute; see
docs/THIRD_PARTY.md)."""
import os, sys, zlib, struct
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
# code points shown in slots 1..31, in order (the first entry is slot 1)
EXTRA = [0x00B0, 0x00B2, 0x00B3, 0x00B5, 0x00B1, 0x00B7, 0x00D7, 0x00F7, 0x00BC, 0x00BD,
         0x00BE, 0x2264, 0x2265, 0x2260, 0x2248, 0x03A9, 0x0394, 0x221A, 0x2030, 0x20AC,
         0x00A3, 0x00E4, 0x00F6, 0x00FC, 0x00C4, 0x00D6, 0x00DC, 0x00E9, 0x00E8, 0x00E0, 0x00F1]
ALIASES = {0x03BC: 0x00B5, 0x2126: 0x03A9}          # Greek mu -> micro sign, ohm sign -> omega
# (ROM font number the UI used, pixel size of DejaVu that matches it)
SIZES = [(26, 13), (28, 18), (30, 25), (31, 36)]
FIRST = 1


def glyphs(px):
    f = ImageFont.truetype(FONT, px)
    asc, desc = f.getmetrics()
    h = asc + desc
    chars = {}
    for code in range(FIRST, 127):
        cp = EXTRA[code - 1] if code < 32 else code
        if code < 32 and code - 1 >= len(EXTRA):
            cp = None
        if cp is None:
            chars[code] = (0, None); continue
        ch = chr(cp)
        adv = int(round(f.getlength(ch)))
        if cp == 32:
            chars[code] = (adv, None); continue
        im = Image.new("L", (adv + 4, h), 0)
        ImageDraw.Draw(im).text((0, 0), ch, font=f, fill=255)
        chars[code] = (adv, im)
    maxw = max(adv for adv, _ in chars.values())
    return h, maxw, chars


def build(px):
    h, maxw, chars = glyphs(px)
    stride = (maxw + 1) // 2                         # L4: two pixels a byte, first in the high nibble
    cell = stride * h
    data = bytearray()
    widths = [0] * 128
    for code in range(FIRST, 127 + 1):
        adv, im = chars.get(code, (0, None))
        widths[code] = adv
        c = bytearray(cell)
        if im is not None:
            for y in range(h):
                for x in range(min(maxw, im.width)):
                    v = im.getpixel((x, y)) >> 4
                    if v:
                        i = y * stride + x // 2
                        c[i] |= v << 4 if x % 2 == 0 else v
        data += c
    metric = bytes(widths) + struct.pack("<IIII", 2, stride, maxw, h)   # format 2 = L4; pointer added at load
    return h, stride, maxw, cell, metric, bytes(data)


def c_array(name, b):
    rows = []
    for k in range(0, len(b), 20):
        rows.append("    " + ", ".join(f"0x{x:02x}" for x in b[k:k + 20]) + ",")
    return f"static const uint8_t {name}[{len(b)}] = {{\n" + "\n".join(rows) + "\n};\n"


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "platform", "ui", "eve_fonts.c")
    parts, table = [], []
    total_z = total = 0
    for rom, px in SIZES:
        h, stride, maxw, cell, metric, data = build(px)
        z = zlib.compress(data, 9)
        total_z += len(z); total += len(data)
        crc = zlib.crc32(data) & 0xFFFFFFFF
        parts.append(c_array(f"z{rom}", z))
        parts.append(c_array(f"m{rom}", metric))
        table.append(f"    {{ {rom}, {h}, {FIRST}, {cell}u, {len(data)}u, 0x{crc:08x}u, z{rom}, {len(z)}u, m{rom} }},")
    enc = []
    for i, cp in enumerate(EXTRA):
        enc.append(f"    {{ 0x{cp:04x}u, {i + 1} }},")
    for a, b in ALIASES.items():
        enc.append(f"    {{ 0x{a:04x}u, {EXTRA.index(b) + 1} }},")
    src = f"""/* eve_fonts.c - GENERATED by tools/mkfont.py: DejaVu Sans as EVE L4 fonts at the sizes
 * of ROM fonts 26/28/30/31, zlib-compressed ({total_z} bytes, {total} bytes in RAM_G).
 * Codes 1..31 hold the symbols in eve_font_extra[]. Do not edit; re-run the tool. */
#include "eve.h"

{''.join(parts)}
const eve_font_t eve_fonts[EVE_FONTS] = {{
{chr(10).join(table)}
}};

const eve_font_char_t eve_font_extra[] = {{
{chr(10).join(enc)}
}};
const unsigned eve_font_n_extra = sizeof eve_font_extra / sizeof eve_font_extra[0];
"""
    open(out, "w").write(src)
    print(f"{out}: {len(SIZES)} fonts, {total} bytes ({total_z} compressed)")


if __name__ == "__main__":
    main()
