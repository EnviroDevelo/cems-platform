#!/usr/bin/env python3
"""Embed web/index.html into platform/net/web_page.c as gzip (reproducible: mtime 0).
Run after editing the page:  python3 tools/embed_web.py"""
import gzip, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
html = (root / "web" / "index.html").read_bytes()
gz = gzip.compress(html, compresslevel=9, mtime=0)
lines = []
for k in range(0, len(gz), 16):
    lines.append("    " + ", ".join(f"0x{b:02x}" for b in gz[k:k + 16]) + ",")
src = f"""/* web_page.c - GENERATED by tools/embed_web.py from web/index.html. Do not edit. */
#include <stdint.h>
const uint32_t web_index_gz_len = {len(gz)}u;   /* {len(html)} bytes uncompressed */
const uint8_t web_index_gz[] = {{
{chr(10).join(lines)}
}};
"""
(root / "platform" / "net" / "web_page.c").write_text(src)
print(f"web_page.c: {len(html)} -> {len(gz)} bytes")
