/* fault_codes.c - writes the published fault and alarm code list (Common Instrument Platform
 * Specification CIP-11.3) from the firmware's own tables, so the document cannot drift from
 * the code:
 *
 *   build/fault_codes --platform   docs/FAULT_CODES.md: the platform's codes (alarms 1-99, the
 *                                  self-test checks, fault record, reset causes, events,
 *                                  firmware update refusals), the same in every product
 *   build/fault_codes              a product's list: its alarms (100+) and its own self-test
 *                                  checks, from whichever application is linked (APP=);
 *                                  exit status 1 if one of its alarms has no .help
 *
 * make fault-codes writes them; make test fails if docs/FAULT_CODES.md is out of date, or if a
 * platform alarm has no help text or an event code no label (exit status 1). */
#include <stdio.h>
#include <string.h>
#include "plat_tasks.h"
#include "plat_alarm.h"
#include "plat_selftest.h"
#include "plat_diag.h"
#include "plat_log.h"
#include "log_csv.h"
#include "fw_update.h"
#include "param.h"

static int missing;                            /* platform entries without their words: an error */

static void cell(const char *s) {              /* a Markdown table cell: no bars or line breaks */
    for (; s && *s; ++s) {
        if (*s == '|') fputs("\\|", stdout);
        else if (*s == '\n') putchar(' ');
        else putchar(*s);
    }
}

static void behaviour(const alarm_def_t *d) {
    const char *sep = "";
    if (d->flags & AL_LATCH)  { printf("%slatching", sep); sep = ", "; }
    if (d->flags & AL_NO_ACK) { printf("%sno acknowledge", sep); sep = ", "; }
    if (d->flags & AL_STOPS)  { printf("%sstops measurement", sep); sep = ", "; }
    if (d->on_delay_ms)  { printf("%son after %.1f s", sep, d->on_delay_ms / 1000.0); sep = ", "; }
    if (d->off_delay_ms) { printf("%soff after %.1f s", sep, d->off_delay_ms / 1000.0); sep = ", "; }
    if (d->route & AR_EMAIL)  { printf("%semail", sep); sep = ", "; }
    if (d->route & AR_MODBUS) { printf("%sModbus", sep); sep = ", "; }
    for (unsigned k = 0; k < ALARM_RELAYS; ++k) if (d->route & AR_RELAY(k)) { printf("%srelay %u", sep, k + 1u); sep = ", "; }
    if (!*sep) putchar('-');
}

static void alarms(bool platform) {
    puts("| ID | Name | Severity | Behaviour (default) | Text | What to check |");
    puts("|---|---|---|---|---|---|");
    for (unsigned id = 1; id <= ALARM_ID_MAX; ++id) {           /* in ID order */
        const alarm_def_t *d = NULL;
        for (size_t i = 0; i < alarm_count(); ++i) if (alarm_def_at(i)->id == id) d = alarm_def_at(i);
        if (!d || (d->id < ALARM_ID_APP_FIRST) != platform) continue;
        printf("| %u | `%s` | %s | ", d->id, d->name, alarm_sev_name(d->severity));
        behaviour(d);
        fputs(" | ", stdout); cell(d->text);
        if (!d->help) { fprintf(stderr, "alarm %u (%s) has no .help\n", d->id, d->name); missing++; }
        fputs(" | ", stdout); cell(d->help ? d->help : "-");
        puts(" |");
    }
}

static int platform_list(void) {
    puts("# Fault and alarm codes");
    puts("");
    puts("The platform's codes, the same in every product of the family (Common Instrument Platform");
    puts("Specification CIP-11.3). Platform alarms are 1-99; each product lists its own from 100 in");
    puts("its own `FAULT_CODES.md`. **Generated by `make fault-codes` from the firmware's tables "
         "(`tools/fault_codes.c`); do not edit by hand.** `make test` fails if it is out of date.");
    puts("");
    puts("## Alarms");
    puts("");
    puts("Severity: status < warning < alarm < fault. The behaviour column is the default; the user");
    puts("can change each alarm's actions (email, Modbus common bit, relays) with parameter 46.");
    puts("Active alarms are in the Modbus registers 10-25 (one bit per ID) and on `/api/alarms`.");
    puts("");
    alarms(true);
    puts("");
    puts("## Start-up self-test checks");
    puts("");
    puts("Parameter 333 and `/api/info` `selftest` (PLATFORM.md 5o). A product's own checks are bits 16-23.");
    puts("");
    puts("| Bit | Check |");
    puts("|---|---|");
    for (unsigned i = 0; i < PLAT_STEST_N; ++i) {
        const char *nm; plat_selftest_get(i, &nm, NULL);
        printf("| %u | `%s` |\n", i, nm);
    }
    puts("");
    puts("## Fault record");
    puts("");
    puts("The last fault before a restart: `/api/info` `last_fault` (code, name, arg), the System screen.");
    puts("");
    puts("| Code | Meaning |");
    puts("|---|---|");
    for (uint32_t f = 0; f <= PLAT_FAULT_HARDFAULT; ++f) { printf("| %u | ", f); cell(plat_fault_text(f)); puts(" |"); }
    puts("");
    puts("## Reset causes");
    puts("");
    puts("The `power_up` event's arg (its detail says it in words).");
    puts("");
    puts("| Code | Cause |");
    puts("|---|---|");
    static const char *const rc[] = { "unknown", "power-on", "reset pin", "software reset (firmware update, restart, after a recorded fault)",
                                      "watchdog", "window watchdog", "brown-out" };
    for (unsigned k = 0; k <= BSP_RESET_BROWNOUT; ++k) printf("| %u | %s |\n", k, rc[k]);
    puts("");
    puts("## Events");
    puts("");
    puts("Event log codes (`/api/log/events`, the event CSV). Codes from 100 are the product's.");
    puts("");
    puts("| Code | Name | Shown as |");
    puts("|---|---|---|");
    for (uint16_t c = 0; c < LOG_EV_APP; ++c) {
        const char *nm = plat_log_event_name(c);
        if (!strcmp(nm, "unknown")) continue;
        log_event_t e; memset(&e, 0, sizeof e); e.code = c;
        char what[32], det[64];
        log_event_text(&e, what, sizeof what, det, sizeof det);
        if (!strcmp(what, "Event")) { fprintf(stderr, "event %u has no label in log_event_text\n", c); missing++; }
        printf("| %u | `%s` | %s |\n", c, nm, what);
    }
    puts("");
    puts("## Firmware update refusals");
    puts("");
    puts("`/api/fw` `last_error` and the web page's message.");
    puts("");
    puts("| Code | Meaning |");
    puts("|---|---|");
    for (int e = 1; e <= FW_E_HARDWARE; ++e) printf("| %d | %s |\n", e, fw_err_name((fw_err_t)e));
    return missing ? 1 : 0;
}

static int product_list(const plat_app_t *app) {
    printf("# %s: fault and alarm codes\n\n", app->ident.product);
    puts("This product's own codes. The platform's (alarms 1-99, self-test checks 0-15, fault record,");
    puts("events) are in the platform's `docs/FAULT_CODES.md`. **Generated by `make fault-codes APP=...`;");
    puts("do not edit by hand.**");
    puts("");
    puts("## Alarms");
    puts("");
    alarms(false);
    puts("");
    puts("## Start-up self-test checks");
    puts("");
    puts("| Bit | Check |");
    puts("|---|---|");
    for (unsigned i = PLAT_STEST_N; i < plat_selftest_count(); ++i) {
        const char *nm; plat_selftest_get(i, &nm, NULL);
        printf("| %u | `%s` |\n", 16u + i - PLAT_STEST_N, nm);
    }
    return missing ? 1 : 0;
}

int main(int argc, char **argv) {
    bool platform = argc > 1 && !strcmp(argv[1], "--platform");
    const plat_app_t *app = app_select();
    if (param_init(app->params, app->n_params) != PERR_OK) { fprintf(stderr, "param table error at %u\n", param_table_error()); return 1; }
    if (platform) {
        if (alarm_init(NULL, 0, 0) != 0 || plat_selftest_init(NULL, 0, 0) != 0) return 1;
        return platform_list();
    }
    int ae = alarm_init(app->alarms, app->n_alarms, 0);
    if (ae) { fprintf(stderr, "alarm table error at id %d\n", ae); return 1; }
    if (plat_selftest_init(app->selftests, app->n_selftests, 0) != 0) { fprintf(stderr, "more than %u self-tests\n", PLAT_STEST_APP_MAX); return 1; }
    return product_list(app);
}
